import type { Value } from "./value.js";

export const FACT_ORIGINS = [
  "listing",
  "recruiter",
  "offer",
  "contract",
  "user",
  "government_rule",
  "derived",
] as const;
export type FactOrigin = (typeof FACT_ORIGINS)[number];

export const EVIDENCE_STATUSES = ["explicit", "inferred", "assumed"] as const;
export type EvidenceStatus = (typeof EVIDENCE_STATUSES)[number];

export const VALIDATION_STATES = ["valid", "conflicting", "superseded"] as const;
export type ValidationState = (typeof VALIDATION_STATES)[number];

export interface SourceReference {
  readonly id: string;
  readonly label?: string;
  readonly uri?: string;
}

export interface Fact<T> {
  readonly value: Value<T>;
  readonly origin: FactOrigin;
  readonly evidenceStatus: EvidenceStatus;
  readonly validationState: ValidationState;
  readonly source?: SourceReference;
  /** ISO 8601 timestamp or date supplied by the caller; never generated by core. */
  readonly observedAt?: string;
  readonly locked: boolean;
}

export interface Assumption {
  readonly code: string;
  readonly message: string;
  readonly affectedPaths: readonly string[];
}

export interface DerivationStep {
  readonly id: string;
  readonly operation: string;
  readonly inputPaths: readonly string[];
  readonly outputPath: string;
  readonly ruleId?: string;
  readonly rounding?: string;
}
