import { createGenerator } from "ts-json-schema-generator";
import { mkdir, readFile, writeFile } from "node:fs/promises";

const generator = createGenerator({
  path: "packages/core/src/contracts/service.ts",
  tsconfig: "packages/core/tsconfig.json",
  type: "HttpContracts",
  expose: "all",
  skipTypeCheck: true,
  additionalProperties: true,
});
const schema = generator.createSchema("HttpContracts");
const contracts = schema.definitions.HttpContracts.properties;
const ref = (key) => ({ $ref: `#/components/schemas/${key}` });
const json = (key) => ({ "application/json": { schema: ref(key) } });
const errors = Object.fromEntries(
  [400, 403, 404, 405, 409, 413, 422, 428, 429, 500, 503].map((code) => [
    code,
    { description: "Request failed; see error.code and request_id.", content: json("error") },
  ]),
);
const revisionParameters = [
  {
    in: "header",
    name: "If-Match",
    description:
      "Quoted revision from GET. Required for replacement; use If-None-Match: * to create.",
    schema: { type: "string" },
  },
  { in: "header", name: "If-None-Match", schema: { type: "string", const: "*" } },
  {
    in: "header",
    name: "Idempotency-Key",
    description: "Optional identity for retrying the last mutation; changed content conflicts.",
    schema: { type: "string", maxLength: 128 },
  },
];
const operation = (response, request, write = false, status = 200) => ({
  ...(request ? { requestBody: { required: true, content: json(request) } } : {}),
  ...(write ? { security: [{ sessionToken: [] }], parameters: revisionParameters } : {}),
  responses: {
    [status]: {
      description: "Success",
      content: json(response),
      headers: {
        "X-Request-ID": { schema: { type: "string" } },
        ...(write || ["profile", "case"].includes(response)
          ? { ETag: { schema: { type: "string" } } }
          : {}),
      },
    },
    ...errors,
  },
});
const paths = {
  "/api/v1": { get: operation("discovery") },
  "/api/v1/rules": { get: operation("rules") },
  "/api/v1/rules/{id}": {
    parameters: [{ in: "path", name: "id", required: true, schema: { type: "string" } }],
    get: operation("rule"),
  },
  "/api/v1/validate": { post: operation("validation", "validationRequest") },
  "/api/v1/calculate": { post: operation("calculation", "calculationRequest") },
  "/api/v1/profile": { get: operation("profile"), put: operation("profileWrite", "profile", true) },
  "/api/v1/cases": {
    get: operation("cases"),
    post: operation("caseWrite", "caseSaveRequest", true, 201),
  },
  "/api/v1/cases/{id}": {
    parameters: [{ in: "path", name: "id", required: true, schema: { type: "string" } }],
    get: operation("case"),
  },
  "/api/v1/openapi.json": { get: { responses: { 200: { description: "This OpenAPI document" } } } },
};
const components = { ...schema.definitions, ...contracts };
const openapi = JSON.parse(
  JSON.stringify({
    openapi: "3.1.0",
    info: {
      title: "NL Compensation local API",
      version: "v1",
      description:
        "Loopback only. Calculation envelopes retain their v1 CLI-compatible shape. Other errors use the common HTTP error contract. Runtime parsers additionally enforce domain invariants such as compatible units and ordered ranges.",
    },
    servers: [{ url: "http://127.0.0.1:3466" }],
    paths,
    components: {
      schemas: components,
      securitySchemes: {
        sessionToken: { type: "apiKey", in: "header", name: "X-NL-Compensation-Token" },
      },
    },
  }).replaceAll("#/definitions/", "#/components/schemas/"),
);
await mkdir("packages/core/src/generated", { recursive: true });
const version = JSON.parse(await readFile("package.json", "utf8")).version;
const entries = Object.entries(contracts)
  .map(
    ([key, value]) =>
      `${JSON.stringify(key)}: {...${JSON.stringify(value)}, definitions: httpDefinitions}`,
  )
  .join(",");
await writeFile(
  "packages/core/src/generated/http.ts",
  `// Generated by scripts/generate-contracts.mjs.\nexport const ENGINE_VERSION = ${JSON.stringify(version)};\nconst httpDefinitions = ${JSON.stringify(schema.definitions)} as const;\nexport const httpSchemas = {${entries}} as const;\nexport const openApiDocument = ${JSON.stringify(openapi)} as const;\n`,
);
console.log("Generated shared HTTP schemas and OpenAPI from public core contracts.");
